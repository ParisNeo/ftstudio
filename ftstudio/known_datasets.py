"""Known Hugging Face datasets the UI offers as one-click suggestions (spec syntax: see data/hf.py).
Add your own in $FTS_HOME/datasets.json: a list of {"spec","name","desc"}. Always read the dataset card for its license."""
import json

from . import config

D = lambda spec, name, desc: {"spec": spec, "name": name, "desc": desc}

BUILTIN = [
    D("ParisNeo/ascii_colors_discussions", "ascii_colors discussions (36 conversations)",
      "Multi-turn Q&A about the ascii_colors library (columns: system_prompt, discussion). Tiny: teaches style and API habits, not exhaustive recall."),
    D("yahma/alpaca-cleaned#2000", "Alpaca cleaned (sample of 2000)",
      "Classic instruction/response set (about 52k rows), cleaned. Answers were generated by an OpenAI model and the card text says non-commercial. Good for a first run."),
    D("databricks/databricks-dolly-15k", "Dolly 15k",
      "15k human-written instructions, some with a context passage. Small enough to use whole. Check the card for the license."),
    D("mlabonne/FineTome-100k#5000", "FineTome (sample of 5000)",
      "High-quality chat data (100k rows) used in Unsloth's Llama 3.1 tutorial. Conversation format, one split."),
    D("HuggingFaceTB/smol-smoltalk@train#5000", "Smol-SmolTalk (sample of 5000)",
      "Synthetic chat data from Hugging Face (about 485k rows, Apache-2.0 per its card). Some rows carry system prompts."),
    D("openai/gsm8k:main@train", "GSM8K math (train split, 7.5k)",
      "Grade-school math word problems with worked answers: a skill you can measure. Train on the train split only if you evaluate on the test split."),
]


def all_datasets() -> list[dict]:
    out = {d["spec"]: d for d in BUILTIN}
    f = config.home() / "datasets.json"
    if f.exists():
        try:
            for d in json.loads(f.read_text(encoding="utf-8")):
                if isinstance(d, dict) and "spec" in d:
                    out[d["spec"]] = {"name": d["spec"], "desc": "", **d}
        except (json.JSONDecodeError, TypeError):
            pass
    return list(out.values())
